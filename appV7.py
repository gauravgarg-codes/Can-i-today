@st.cache_data(ttl=1800) # Cache for 30 mins (instant load if clicked again)
def fetch_regional_news(region):
    try:
        tf_client = TinyFish(api_key=TF_KEY)
        
        # 1. Search for recent news
        query = f"latest traffic news OR pollution rules OR GRAP updates for {region} after:2026-10-01"
        hits = tf_client.search.query(query=query)
        
        if not hits.results:
            return {"error": "No recent news found for this region."}
            
        # Fetch only top 2 results for speed
        urls = [r.url for r in hits.results[:2]] 
        
        # 2. Fetch content
        fetched_data = tf_client.fetch.get_contents(urls=urls, format="markdown")
        combined_text = ""
        for item in fetched_data.results:
            if item.text:
                # Truncate to 3000 chars per article to speed up LLM processing
                truncated_text = item.text[:3000] 
                combined_text += f"\n\n--- SOURCE: {item.url} ---\n{truncated_text}"
                
        if not combined_text:
            return {"error": "Could not extract text from news articles."}
            
        # 3. Gemini LLM to extract structured headlines
        genai_client = genai.Client(api_key=GEMINI_KEY)
        prompt = f"""
        You are an AI news summarizer tracking traffic and environmental regulations.
        Based on the following documents, extract the top 3 recent news headlines or regulatory advisories for the region: {region}.
        
        Documents: {combined_text}
        
        Return strictly a JSON array of objects with these keys:
        - "headline": The main title of the news/update.
        - "summary": A 1-2 sentence summary of what it means for a driver.
        - "source_url": The URL of the source.
        
        Output JSON:
        """
        
        response = genai_client.models.generate_content(model='gemini-3.8-flash', contents=prompt)
        raw_text = response.text.replace("```json", "").replace("```", "").strip()
        news_data = json.loads(raw_text)
        
        return news_data
        
    except Exception as e:
        return {"error": str(e)}

