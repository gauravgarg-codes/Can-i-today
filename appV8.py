class PDF(FPDF):
    def header(self):
        self.set_font("helvetica", "B", 16)
        self.set_text_color(0, 0, 0)
        self.cell(0, 10, "CAN I TODAY? - Compliance Report", 0, 1, "L")
        self.set_font("helvetica", "I", 10)
        self.set_text_color(100, 100, 100)
        self.cell(0, 10, "Generated by AI Rules Engine", 0, 1, "L")
        self.line(10, 30, 200, 30)
        self.ln(10)

    def footer(self):
        self.set_y(-15)
        self.set_font("helvetica", "I", 8)
        self.set_text_color(150, 150, 150)
        self.cell(
            0, 10,
            f"Page {self.page_no()} | Informational tool. Verify with official orders.",
            0, 0, "C",
        )


def create_pdf(profile: dict, result: dict) -> bytes:
    pdf = PDF()
    pdf.add_page()

    # 1. Profile
    pdf.set_font("helvetica", "B", 12)
    pdf.set_text_color(255, 79, 0)
    pdf.cell(0, 8, "1. VEHICLE PROFILE", 0, 1)

    pdf.set_font("helvetica", "", 10)
    pdf.set_text_color(0, 0, 0)
    for label, key in [
        ("Category:",      "category"),
        ("Fuel Type:",     "fuel"),
        ("Emission Norm:", "emission_norm"),
        ("Registered In:", "registered_in"),
        ("Travel Date:",   "travel_date"),
        ("Destination:",   "traveling_region"),
    ]:
        pdf.cell(40, 8, label, 0, 0)
        pdf.cell(0, 8, str(profile.get(key)), 0, 1)

    pdf.ln(5)

    # 2. Verdict
    status = result.get("status", "Unable to verify").upper()
    pdf.set_font("helvetica", "B", 12)
    pdf.set_text_color(255, 79, 0)
    pdf.cell(0, 8, "2. ASSESSMENT VERDICT", 0, 1)

    pdf.set_font("helvetica", "B", 14)
    if "RESTRICT" in status or "प्रतिबंध" in status:
        pdf.set_text_color(255, 0, 0)
        status = "RESTRICTED"
    elif "ALLOW" in status or "अनुमत" in status:
        pdf.set_text_color(0, 150, 0)
        status = "ALLOWED"
    else:
        pdf.set_text_color(255, 165, 0)
        status = "UNABLE TO VERIFY"

    pdf.cell(0, 10, f"STATUS: {status}", 0, 1)
    pdf.ln(5)

    # 3. Summary
    pdf.set_font("helvetica", "B", 12)
    pdf.set_text_color(255, 79, 0)
    pdf.cell(0, 8, "3. AI SUMMARY", 0, 1)

    pdf.set_font("helvetica", "", 10)
    pdf.set_text_color(50, 50, 50)
    summary = result.get("summary", "No summary provided.")
    clean_summary = summary.encode("ascii", "ignore").decode("ascii")
    if not clean_summary.strip():
        clean_summary = "Summary available in application UI."
    pdf.multi_cell(0, 6, clean_summary)
    pdf.ln(5)

    # 4. Evidence
    pdf.set_font("helvetica", "B", 12)
    pdf.set_text_color(255, 79, 0)
    pdf.cell(0, 8, "4. LEGAL EVIDENCE & SOURCE", 0, 1)

    pdf.set_font("courier", "", 9)
    pdf.set_text_color(30, 30, 30)
    evidence = result.get("evidence", "No evidence extracted.")
    clean_evidence = evidence.encode("ascii", "ignore").decode("ascii")
    if not clean_evidence.strip():
        clean_evidence = "Evidence available in application UI."
    pdf.multi_cell(0, 5, clean_evidence)

    return bytes(pdf.output())


