def read_sheet(sheet_name: str) -> list:
    url = f"{WEB_APP_URL}?sheet={sheet_name}"
    try:
        res = requests.get(url, timeout=10)
        if res.status_code == 200:
            data = res.json()
            if isinstance(data, list) and len(data) > 1:
                return data[1:]
            return []
    except Exception as e:
        st.error(f"Database read error: {e}")
        return []
    return []


def write_sheet(sheet_name: str, data_list: list) -> bool:
    url = f"{WEB_APP_URL}?sheet={sheet_name}"
    try:
        requests.post(url, json=data_list, timeout=10)
        return True
    except Exception as e:
        st.error(f"Database write error: {e}")
        return False


def update_vehicle_profile(email: str, vehicle_data: list) -> bool:
    url = f"{WEB_APP_URL}?action=update_vehicle&email={email}"
    try:
        requests.post(url, json=vehicle_data, timeout=10)
        return True
    except Exception:
        return False


