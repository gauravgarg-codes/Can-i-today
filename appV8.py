@st.cache_data(ttl=1800)
def fetch_regional_news(region: str, lang: str):
    try:
        tf_client = TinyFish(api_key=TF_KEY)
        query = (
            f"latest traffic news OR pollution rules OR GRAP updates "
            f"for {region} after:2026-10-01"
        )
        hits = tf_client.search.query(query=query)

        if not hits.results:
            return {"error": "No recent news found for this region."}

        urls = [r.url for r in hits.results[:2]]
        fetched_data = tf_client.fetch.get_contents(urls=urls, format="markdown")

        combined_text = ""
        for item in fetched_data.results:
            if item.text:
                combined_text += f"\n\n--- SOURCE: {item.url} ---\n{item.text[:3000]}"

        if not combined_text:
            return {"error": "Could not extract text from news articles."}

        genai_client = genai.Client(api_key=GEMINI_KEY)
        prompt = f"""
        You are an AI news summarizer.
        Based on the documents, extract the top 3 recent news headlines or
        regulatory advisories for the region: {region}.
        Output Language: {lang}.
        Documents: {combined_text}

        Return strictly a JSON array of objects with these keys:
        - "headline": The main title.
        - "summary": A 1-2 sentence summary.
        - "source_url": The URL.
        """

        response = genai_client.models.generate_content(
            model="gemini-3.8-flash", contents=prompt
        )
        raw_text = response.text.replace("```json", "").replace("```", "").strip()
        return json.loads(raw_text)

    except Exception as e:
        return {"error": str(e)}


