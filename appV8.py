def _secret(key: str, fallback: str) -> str:
    """Read from env → Streamlit secrets → hardcoded fallback."""
    if os.getenv(key):
        return os.getenv(key)
    try:
        if key in st.secrets:
            return st.secrets[key]
    except Exception:
        pass
    return fallback


